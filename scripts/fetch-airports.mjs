// Builds src/lib/data/airports.ts from OurAirports (public domain, ourairports.com/data).
// Keeps airports with scheduled flights and an IATA code: every large airport in the
// world, plus medium airports in India and nearby countries Indians fly to often.
// Run: node scripts/fetch-airports.mjs   (free, no key)
import { writeFileSync } from "node:fs";

const AIRPORTS_URL = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const COUNTRIES_URL = "https://davidmegginson.github.io/ourairports-data/countries.csv";
/** Countries where medium airports are kept too. */
const MEDIUM = new Set(["IN", "NP", "LK", "MV", "BT", "BD", "AE", "OM", "QA", "BH", "KW", "SA", "TH", "MY", "SG", "ID", "VN", "MU", "SC", "LK"]);

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}

const [airports, countries] = await Promise.all(
  [AIRPORTS_URL, COUNTRIES_URL].map(async (u) => {
    const res = await fetch(u);
    if (!res.ok) throw new Error(`${u}: ${res.status}`);
    return parseCsv(await res.text());
  }),
);
const countryName = Object.fromEntries(countries.map((c) => [c.code, c.name]));

const keep = airports.filter(
  (a) =>
    a.scheduled_service === "yes" &&
    /^[A-Z]{3}$/.test(a.iata_code) &&
    (a.type === "large_airport" || (a.type === "medium_airport" && MEDIUM.has(a.iso_country))),
);
const seen = new Set();
const lines = [];
for (const a of keep.sort((x, y) => x.iata_code.localeCompare(y.iata_code))) {
  if (seen.has(a.iata_code)) continue;
  seen.add(a.iata_code);
  const city = (a.municipality || a.name).replace(/\s*\(.*\)$/, "");
  lines.push(
    `  [${JSON.stringify(a.iata_code)},${JSON.stringify(city)},${JSON.stringify(a.iso_country)},${JSON.stringify(a.continent)},${(+a.latitude_deg).toFixed(3)},${(+a.longitude_deg).toFixed(3)}],`,
  );
}
const used = [...new Set(keep.map((a) => a.iso_country))].sort();
const names = used.map((c) => `${c}:${JSON.stringify(countryName[c] ?? c)}`).join(",");

writeFileSync(
  new URL("../src/lib/data/airports.ts", import.meta.url),
  `// Generated by scripts/fetch-airports.mjs from OurAirports (public domain). Do not edit by hand.
// ${lines.length} airports with scheduled flights: all large airports, plus medium ones in India and nearby.

/** [IATA code, city, ISO country, continent (AF AN AS EU NA OC SA), latitude, longitude] */
export type AirportRow = readonly [code: string, city: string, country: string, continent: string, lat: number, lon: number];

export const AIRPORTS: readonly AirportRow[] = [
${lines.join("\n")}
];

export const COUNTRY_NAMES: Record<string, string> = {${names}};
`,
);
console.log(`Wrote ${lines.length} airports in ${used.length} countries`);
